package com.elemental.vibium;

import com.vibium.Browser;
import com.vibium.Page;
import com.vibium.Vibium;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

public class BasicAuthTest {
    private static final String MESSAGE = "Congratulations! You must have the proper credentials.";

    Browser browser;
    Page page;

    @BeforeEach
    public void beforeEach() {
        browser = Vibium.start();
        page = browser.page();
    }

    @AfterEach
    public void afterEach() {
        if (browser != null) {
            browser.stop();
        }
    }

    @Test
    public void basicAuth() {
        page.go("https://admin:admin@the-internet.herokuapp.com/basic_auth");

        Assertions.assertEquals(MESSAGE, page.find(".example p").text());
    }
}
